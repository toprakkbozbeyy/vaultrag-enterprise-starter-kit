"""VaultRAG Lite - Streamlit chat UI.

Talks only to the Lite FastAPI backend (RAG_API_URL).
Run standalone:
    streamlit run app.py
"""

from __future__ import annotations

import os
from typing import Any

import requests
import streamlit as st

API_URL = os.getenv("RAG_API_URL", "http://localhost:8000").rstrip("/")
WHOP_URL = os.getenv("WHOP_URL", "https://whop.com/checkout/YOUR_PRODUCT_ID")
UPLOAD_TIMEOUT = 600  # embedding a big PDF on CPU can take minutes
QUERY_TIMEOUT = 300

st.set_page_config(page_title="VaultRAG Lite - Private Document Q&A", page_icon="\U0001F512", layout="wide")


# ---------------------------------------------------------------------------
# HTTP helpers
# ---------------------------------------------------------------------------
def error_text(resp: requests.Response) -> str:
    try:
        return str(resp.json().get("detail") or resp.text[:300])
    except ValueError:
        return f"HTTP {resp.status_code}: {resp.text[:300]}"


@st.cache_data(ttl=5, show_spinner=False)
def fetch_health() -> dict[str, Any] | None:
    try:
        return requests.get(f"{API_URL}/health", timeout=8).json()
    except (requests.RequestException, ValueError):
        return None


def fetch_documents() -> list[dict[str, Any]]:
    resp = requests.get(f"{API_URL}/api/v1/documents", timeout=30)
    resp.raise_for_status()
    return resp.json()["documents"]


# ---------------------------------------------------------------------------
# Session state
# ---------------------------------------------------------------------------
st.session_state.setdefault("messages", [])
st.session_state.setdefault("uploader_key", 0)

# ---------------------------------------------------------------------------
# Sidebar: status, upload, library, upgrade note
# ---------------------------------------------------------------------------
with st.sidebar:
    st.title("\U0001F512 VaultRAG Lite")
    st.caption("Your documents never leave this machine.")

    health = fetch_health()
    if health is None:
        st.error("Backend unreachable")
    elif health["status"] == "ok":
        st.success(f"Ready · {health['llm_model']} · {health['indexed_chunks']} chunks")
    else:
        st.warning(health["ollama"].get("detail") or "Backend degraded")

    st.divider()
    st.subheader("Upload documents")
    uploads = st.file_uploader(
        "PDF, TXT or Markdown (max 10 MB each)",
        type=["pdf", "txt", "md"],
        accept_multiple_files=True,
        key=f"uploader_{st.session_state.uploader_key}",
    )
    if uploads and st.button("Index documents", type="primary", use_container_width=True):
        with st.spinner("Parsing and embedding locally... large files can take a while on CPU."):
            try:
                resp = requests.post(
                    f"{API_URL}/api/v1/upload",
                    files=[("files", (f.name, f.getvalue())) for f in uploads],
                    timeout=UPLOAD_TIMEOUT,
                )
            except requests.RequestException as exc:
                st.error(f"Upload failed: {exc}")
            else:
                if resp.status_code >= 400:
                    st.error(error_text(resp))
                else:
                    for r in resp.json()["results"]:
                        if r["status"] == "indexed":
                            st.success(f"{r['source']}: {r['chunks']} chunks")
                        else:
                            st.error(f"{r['source']}: {r['detail']}")
                    st.session_state.uploader_key += 1  # reset the widget

    st.divider()
    st.subheader("Library")
    try:
        docs = fetch_documents()
    except requests.RequestException:
        docs = []
        st.caption("Library unavailable.")
    if docs:
        for d in docs:
            st.markdown(f"\U0001F4C4 **{d['source']}** · {d['chunks']} chunks")
    else:
        st.caption("No documents yet.")

    st.divider()
    st.markdown(
        "**Need more than Lite?**  \n"
        "API-key auth, validated citations, DOCX/CSV, per-document erasure and GPU profile.  \n"
        f"[**Get VaultRAG Enterprise →**]({WHOP_URL})"
    )
    if st.button("Clear chat", use_container_width=True):
        st.session_state.messages = []
        st.rerun()

# ---------------------------------------------------------------------------
# Chat
# ---------------------------------------------------------------------------
st.header("Ask your documents")
st.caption("Answers are generated by a local LLM through Ollama. No cloud API, no telemetry.")


def render_sources(sources: list[dict[str, Any]]) -> None:
    if not sources:
        return
    with st.expander(f"Retrieved passages ({len(sources)})"):
        for i, s in enumerate(sources, start=1):
            page = f" · page {s['page']}" if s.get("page") else ""
            st.markdown(f"**[{i}] {s['source']}**{page} · similarity {s['score']:.2f}")
            st.caption(s["snippet"])


for msg in st.session_state.messages:
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])
        render_sources(msg.get("sources", []))

if question := st.chat_input("Ask a question about your uploaded documents..."):
    st.session_state.messages.append({"role": "user", "content": question})
    with st.chat_message("user"):
        st.markdown(question)

    with st.chat_message("assistant"):
        with st.spinner("Searching and thinking locally..."):
            try:
                resp = requests.post(f"{API_URL}/api/v1/query", json={"question": question}, timeout=QUERY_TIMEOUT)
            except requests.RequestException as exc:
                answer, sources = f"⚠️ Could not reach the backend: {exc}", []
            else:
                if resp.status_code >= 400:
                    answer, sources = f"⚠️ {error_text(resp)}", []
                else:
                    body = resp.json()
                    answer, sources = body["answer"], body["sources"]
                    answer += f"\n\n*{body['model']} · {body['latency_ms'] / 1000:.1f}s*"
        st.markdown(answer)
        render_sources(sources)

    st.session_state.messages.append({"role": "assistant", "content": answer, "sources": sources})
